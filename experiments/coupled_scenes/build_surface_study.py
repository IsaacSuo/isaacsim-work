"""Build five editable surface-study layouts inside the warehouse environment.

Run with Blender --background --python-exit-code 1 --python THIS -- --output DIR.
No particles, fluid animation or simulation are generated by this builder.
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

import bpy
from bpy_extras.object_utils import world_to_camera_view
from mathutils import Matrix, Vector

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from coupled_scene.surface_study import actuator_spec, collision_panels, motion_state


def convert(p):
    return Vector((p[0], -p[2], p[1]))


def material(name, colour, roughness=0.3, transmission=0.0, metallic=0.0):
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    m.node_tree.nodes.clear()
    p = m.node_tree.nodes.new("ShaderNodeBsdfPrincipled")
    out = m.node_tree.nodes.new("ShaderNodeOutputMaterial")
    m.node_tree.links.new(p.outputs["BSDF"], out.inputs["Surface"])
    p.inputs["Base Color"].default_value = (*colour, 1)
    p.inputs["Roughness"].default_value = roughness
    p.inputs["Metallic"].default_value = metallic
    p.inputs["Transmission Weight"].default_value = transmission
    p.inputs["IOR"].default_value = 1.333 if name == "REFERENCE_WATER" else 1.46
    return m


def move_to(obj, collection):
    for owner in list(obj.users_collection):
        owner.objects.unlink(obj)
    collection.objects.link(obj)
    return obj


def box(name, centre, size, mat, collection, parent=None, bevel=0.0):
    bpy.ops.mesh.primitive_cube_add(size=1)
    obj = move_to(bpy.context.object, collection)
    obj.name = name
    obj.parent = parent
    obj.location = convert(centre)
    obj.scale = (size[0], size[2], size[1])
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    if mat:
        obj.data.materials.append(mat)
    if bevel:
        modifier = obj.modifiers.new("Edge finish", "BEVEL")
        modifier.width, modifier.segments = bevel, 3
    return obj


def empty(name, location, collection):
    obj = bpy.data.objects.new(name, None)
    collection.objects.link(obj)
    obj.location = convert(location)
    obj.empty_display_size = 0.1
    return obj


def text_label(name, content, local_location, size, mat, collection, parent):
    data = bpy.data.curves.new(name, "FONT")
    data.body, data.size = content, size
    data.extrude = 0.0001
    obj = bpy.data.objects.new(name, data)
    collection.objects.link(obj)
    obj.parent = parent
    obj.location = convert(local_location)
    # Text lies on the forward vertical face, with local up = Blender Z.
    obj.rotation_euler = (math.pi / 2, 0, 0)
    data.materials.append(mat)
    return obj


def animate(obj, base, motion, duration, fps):
    for frame in range(1, int(duration * fps) + 2):
        p, _ = motion_state(motion, (frame - 1) / fps)
        obj.location = convert([a + b for a, b in zip(base, p)])
        obj.keyframe_insert(data_path="location", frame=frame)


def write_collision_usd(path, cfg, case, tank_origin):
    """Solver-independent Y-up collider asset, excluding decorative/reference water."""
    fps, duration = cfg["fps"], case["duration_s"]
    end = int(duration * fps) + 1
    lines = ["#usda 1.0", "(", '    defaultPrim = "SurfaceStudy"', '    upAxis = "Y"',
             "    metersPerUnit = 1", f"    timeCodesPerSecond = {fps}",
             f"    startTimeCode = 1", f"    endTimeCode = {end}", ")", 'def Xform "SurfaceStudy" {']
    def vec(values):
        return "(" + ", ".join(f"{v:.10g}" for v in values) + ")"
    def body(name, base, shapes):
        motion = case["motion"] if case["motion"] and case["motion"]["target"] == name else None
        api = ' (prepend apiSchemas = ["PhysicsRigidBodyAPI"])' if motion else ""
        lines.append(f'    def Xform "{name}"{api} {{')
        if motion:
            lines.extend(['        bool physics:rigidBodyEnabled = true', '        bool physics:kinematicEnabled = true'])
            lines.append("        double3 xformOp:translate.timeSamples = {")
            for f in range(1, end+1):
                p, _ = motion_state(motion, (f-1)/fps)
                lines.append(f"            {f}: {vec([a+b for a,b in zip(base,p)])},")
            lines.append("        }")
        else:
            lines.append(f"        double3 xformOp:translate = {vec(base)}")
        lines.append('        uniform token[] xformOpOrder = ["xformOp:translate"]')
        for label, shape, centre, dimensions in shapes:
            lines.append(f'        def {shape} "{label}" (prepend apiSchemas = ["PhysicsCollisionAPI"]) {{')
            lines.append('            bool physics:collisionEnabled = true')
            lines.append(f"            double3 xformOp:translate = {vec(centre)}")
            if shape == "Cube":
                lines.extend(["            double size = 1", f"            double3 xformOp:scale = {vec(dimensions)}",
                          '            uniform token[] xformOpOrder = ["xformOp:translate", "xformOp:scale"]'])
            else:
                lines.extend([f"            double radius = {dimensions[0]}", f"            double height = {dimensions[1]}",
                              '            uniform token axis = "Y"', '            uniform token[] xformOpOrder = ["xformOp:translate"]'])
            lines.append("        }")
        lines.append("    }")
    body("Tank", tank_origin, [(n, "Cube", p, s) for n,p,s in collision_panels(cfg["tank"])])
    a = actuator_spec(case["actuator"], cfg["tank"])
    if a:
        base = [x+y for x,y in zip(tank_origin, a["centre"])]
        dimensions = a.get("size", [a.get("radius"), a.get("height")])
        body(case["actuator"], base, [("ContactShape", a["shape"], [0,0,0], dimensions)])
    lines.append("}")
    path.write_text("\n".join(lines)+"\n", encoding="utf-8")


def camera_report(camera, scene):
    world_cv = camera.matrix_world @ Matrix.Diagonal((1, -1, -1, 1))
    width, height = scene.render.resolution_x, scene.render.resolution_y
    focal = width * camera.data.lens / camera.data.sensor_width
    return {"name": camera.name, "resolution": [width,height],
            "K": [[focal,0,width/2],[0,focal,height/2],[0,0,1]],
            "camera_to_world_blender_cv": [list(row) for row in world_cv],
            "world_to_camera_cv": [list(row) for row in world_cv.inverted()],
            "coordinate_note": "World: Blender Z-up. Camera: +X right, +Y down, +Z forward. Isaac (x,y,z) -> Blender (x,-z,y)."}


def build(cfg, case, output, environment, samples):
    bpy.ops.wm.open_mainfile(filepath=str(environment))
    scene = bpy.context.scene
    collection = bpy.data.collections.new("SurfaceStudy")
    scene.collection.children.link(collection)
    scene.unit_settings.system = "METRIC"
    scene.unit_settings.scale_length = 1
    floor = cfg["placement_isaac"]
    tank = cfg["tank"]
    origin = [floor[0], floor[1]+tank["floor_above_support_m"], floor[2]]
    root = empty("Tank", origin, collection)
    steel = material("Slate frame", (0.06,0.085,0.095), 0.27, metallic=0.45)
    base_mat = material("Ceramic basin floor", (0.50,0.60,0.61), 0.38)
    glass = material("Clear observation walls", (0.97,0.99,1), 0.055, 1)
    water = material("REFERENCE_WATER", (0.58,0.84,0.88), 0.08, 0.9)
    orange = material("Actuator copper", (0.65,0.20,0.06), 0.28, metallic=0.25)
    white = material("Markings", (0.90,0.94,0.94), 0.45)
    # Stand is fixed in world space; only the tank moves in the sloshing case.
    box("Workbench", [floor[0],origin[1]-0.10,floor[2]], [2.08,0.10,1.24], steel, collection, bevel=0.018)
    for x in [-0.87,0.87]:
        for z in [-0.48,0.48]:
            box("Stand leg", [floor[0]+x,floor[1]+0.285,floor[2]+z], [.065,.57,.065], steel, collection, bevel=.008)
    x,h,z = tank["inner_size_m"]
    visible_tank = dict(tank, proxy_thickness_m=tank["glass_thickness_m"])
    for name,p,size in collision_panels(visible_tank):
        box("Visible_"+name,p,size,base_mat if name=="Floor" else glass,collection,root,.002)
    for p,s in [([0,-.025,-z/2-.018],[x+.07,.035,.025]),([0,-.025,z/2+.018],[x+.07,.035,.025])]:
        box("Lower rail",p,s,steel,collection,root,.003)
    # Low-contrast grid on the floor provides an honest length reference.
    for i in range(-7,8):
        box("Floor grid X",[i*.1,.0003,0],[.0008,.0004,z-.02],white,collection,root)
    for i in range(-4,5):
        box("Floor grid Z",[0,.0003,i*.1],[x-.02,.0004,.0008],white,collection,root)
    for mm in range(0,261,20):
        yy=mm/1000
        box(f"Depth mark {mm} mm",[-.735,yy,z/2+.0125],[.035,.0015,.0008],white,collection,root)
        text_label(f"Depth label {mm}",str(mm),[-.785,yy+.002,z/2+.013],.010,white,collection,root)
    depth=tank["reference_water_depth_m"]
    proxy=box("REFERENCE_WATER_NOT_SIMULATED",[0,depth/2,0],[x-.002,depth,z-.002],water,collection,root)
    proxy["purpose"]="Static design water level only; remove before importing simulated fluid."
    proxy["physics_collision"]=False
    text_label("Reference label",f"SURFACE STUDY  /  REFERENCE LEVEL {depth*1000:.0f} mm",[-.87,-.113,.622],.022,white,collection,root)
    motion = case["motion"]
    if motion and motion["target"] == "Tank":
        animate(root, origin, motion, case["duration_s"], cfg["fps"])
        for zz in [-.4,.4]:
            box("Slide track",[floor[0],origin[1]-.055,floor[2]+zz],[1.98,.025,.035],orange,collection,bevel=.003)
    actuator=actuator_spec(case["actuator"],tank)
    if actuator:
        base=[a+b for a,b in zip(origin,actuator["centre"])]
        drive=empty(case["actuator"],base,collection)
        if actuator["shape"]=="Cylinder":
            bpy.ops.mesh.primitive_cylinder_add(vertices=64,radius=actuator["radius"],depth=actuator["height"])
            disc=move_to(bpy.context.object,collection)
            disc.name="Plunger contact disc";disc.parent=drive;disc.location=(0,0,0);disc.data.materials.append(orange)
            box("Plunger rod",[0,.16,0],[.016,.30,.016],steel,collection,drive,.003)
            box("Plunger crossbeam",[floor[0],origin[1]+.48,floor[2]], [.055,.045,1.1],steel,collection,bevel=.006)
            for zz in [-.55,.55]:
                box("Plunger support",[floor[0],origin[1]+.205,floor[2]+zz],[.04,.55,.04],steel,collection,bevel=.004)
        else:
            box("Paddle contact plate",[0,0,0],actuator["size"],orange,collection,drive,.002)
            box("Paddle upper rod",[0,.18,0],[.014,.25,.014],steel,collection,drive,.003)
        animate(drive,base,motion,case["duration_s"],cfg["fps"])
    # Hidden collision inspection objects; the portable USD below is authoritative.
    collisions=bpy.data.collections.new("COLLISION_PROXIES_inspection_only")
    scene.collection.children.link(collisions)
    for name,p,size in collision_panels(tank):
        obj=box("Proxy_"+name,p,size,None,collisions,root)
        obj.display_type="WIRE";obj.hide_render=True;obj.hide_set(True)
    world=bpy.data.worlds.new("Surface study environment")
    scene.world=world;world.use_nodes=True
    nodes=world.node_tree.nodes
    nodes.clear()
    background=nodes.new("ShaderNodeBackground")
    world_output=nodes.new("ShaderNodeOutputWorld")
    env=nodes.new("ShaderNodeTexEnvironment")
    env.image=bpy.data.images.load(str(environment.parent/"HDRI/bryanston_park_sunrise_8k.exr"),check_existing=True)
    background.inputs["Strength"].default_value=.65
    world.node_tree.links.new(env.outputs["Color"],background.inputs["Color"])
    world.node_tree.links.new(background.outputs["Background"],world_output.inputs["Surface"])
    target=convert([origin[0],origin[1]+.08,origin[2]])
    for name,local,power,size in [("Key",[-.8,2.3,-.8],700,1.8),("Rim",[.8,1.8,.8],500,1.3)]:
        light=bpy.data.lights.new(name,"AREA");light.energy=power;light.shape="DISK";light.size=size
        obj=bpy.data.objects.new(name,light);collection.objects.link(obj)
        obj.location=convert([a+b for a,b in zip(origin,local)])
        obj.rotation_euler=(target-obj.location).to_track_quat("-Z","Y").to_euler()
    scene.render.engine="CYCLES";scene.cycles.samples=samples;scene.cycles.use_denoising=True
    prefs=bpy.context.preferences.addons["cycles"].preferences
    prefs.compute_device_type="OPTIX";prefs.get_devices()
    for device in prefs.devices:device.use=device.type!="CPU"
    scene.cycles.device="GPU"
    scene.render.resolution_x,scene.render.resolution_y=cfg["camera"]["resolution"]
    scene.render.resolution_percentage=100
    scene.render.image_settings.file_format="PNG"
    scene.render.fps=cfg["fps"];scene.frame_start=1;scene.frame_end=int(case["duration_s"]*cfg["fps"])+1
    scene.view_settings.view_transform="AgX";scene.view_settings.exposure=0
    cameras=[]
    for i in range(cfg["camera"]["count"]):
        angle=math.radians(-55+i*360/cfg["camera"]["count"])
        data=bpy.data.cameras.new(f"View_{i:02d}");data.lens=cfg["camera"]["lens_mm"];data.sensor_width=36;data.sensor_fit="HORIZONTAL"
        cam=bpy.data.objects.new(data.name,data);collection.objects.link(cam)
        cam.location=target+Vector((cfg["camera"]["radius_m"]*math.cos(angle),cfg["camera"]["radius_m"]*math.sin(angle),cfg["camera"]["height_above_tank_m"]))
        cam.rotation_euler=(target-cam.location).to_track_quat("-Z","Y").to_euler();cameras.append(cam)
    scene.camera=cameras[0];scene.frame_set(1);bpy.context.view_layer.update()
    reports=[camera_report(c,scene) for c in cameras]
    case_dir=output/case["id"];case_dir.mkdir(parents=True,exist_ok=True)
    (case_dir/"cameras.json").write_text(json.dumps(reports,indent=2),encoding="utf-8")
    spec={"schema":1,"product":"surface_study_server_handoff","status":"layout_only_runtime_adapter_required",
          "environment":cfg["environment"],"tank_origin_isaac":origin,"tank":tank,"case":case,
          "fps":cfg["fps"],"frame_count":scene.frame_end,"fluid":{
              "initialization":"prefilled_then_settled","exclude_solid_colliders":True,
              "reference_water_depth_m":depth,"reference_mesh_is_not_fluid":True,
              "rendered_water_animation":False},
          "collider_asset":"colliders.usda","motion_function":"coupled_scene.surface_study.motion_state",
          "motion_sampling":"Evaluate at native solver substeps; USD animation is a 60 Hz design preview.",
          "camera_file":"cameras.json","existing_pbd_pour_runner_compatible":False}
    (case_dir/"scene_spec.json").write_text(json.dumps(spec,indent=2,ensure_ascii=False),encoding="utf-8")
    samples_table=[]
    for frame in range(1,scene.frame_end+1):
        seconds=(frame-1)/cfg["fps"]
        displacement,velocity=motion_state(motion,seconds)
        samples_table.append({"frame":frame,"seconds":seconds,"displacement_isaac_m":displacement,"velocity_isaac_m_s":velocity})
    (case_dir/"motion_samples.json").write_text(json.dumps(samples_table,indent=2),encoding="utf-8")
    write_collision_usd(case_dir/"colliders.usda",cfg,case,origin)
    scene["surface_study_case"]=case["id"];scene["fluid_simulated"]=False
    scene["instructions"]="REFERENCE_WATER_NOT_SIMULATED is a layout placeholder; native fluid must replace it."
    # Save an immediately useful camera view in the editable file.
    for screen in bpy.data.screens:
        for area in screen.areas:
            if area.type=="VIEW_3D":area.spaces.active.region_3d.view_perspective="CAMERA"
    bpy.ops.wm.save_as_mainfile(filepath=str(case_dir/(case["id"]+".blend")))
    for index in ([0,2,4,6] if case["id"]=="01_still_water" else [0]):
        scene.camera=cameras[index]
        scene.render.filepath=str(case_dir/f"view_{index:02d}.png")
        bpy.ops.render.render(write_still=True)
    if motion:
        peak=max(samples_table,key=lambda s:sum(v*v for v in s["displacement_isaac_m"]))
        scene.camera=cameras[0];scene.frame_set(peak["frame"])
        scene.render.filepath=str(case_dir/"action_peak.png")
        bpy.ops.render.render(write_still=True)
        (case_dir/"preview_pose.json").write_text(json.dumps(peak,indent=2),encoding="utf-8")
    print(f"[built] {case['id']} {case_dir}",flush=True)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output",type=Path,required=True)
    parser.add_argument("--environment",type=Path,default=Path(r"Y:\scenes\warehouse.blend"))
    parser.add_argument("--samples",type=int,default=48)
    parser.add_argument("--cases",nargs="*")
    args=parser.parse_args(sys.argv[sys.argv.index("--")+1:])
    cfg=json.loads((ROOT/"configs/surface_study_scene.json").read_text())
    for case in cfg["cases"]:
        if args.cases and case["id"] not in args.cases:continue
        build(cfg,case,args.output.resolve(),args.environment,args.samples)


if __name__=="__main__":
    main()
